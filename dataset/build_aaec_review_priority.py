"""
Analyze AAEC Nyaya annotation sheet and build a priority review subset.

Selection:
  - All rows with candidate_pramana != Anumana
  - Random sample of 200 Anumana rows

Outputs:
  - dataset/processed/aaec_review_priority.csv
  - reports/aaec_nyaya_distribution.md

Usage:
    python dataset/build_aaec_review_priority.py
"""

from __future__ import annotations

import random
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from dataset.build_aaec_nyaya_annotation_sheet import HEURISTIC_CUES, PRAMANA_LABELS
from reports._common import dataframe_to_markdown, ensure_reports_dir

INPUT_CSV = PROJECT_ROOT / "dataset" / "processed" / "aaec_nyaya_annotation_sheet.csv"
OUTPUT_CSV = PROJECT_ROOT / "dataset" / "processed" / "aaec_review_priority.csv"
REPORT_OUT = PROJECT_ROOT / "reports" / "aaec_nyaya_distribution.md"

ANUMANA_SAMPLE = 200
RANDOM_SEED = 42


def _cue_hit_counts(df: pd.DataFrame) -> dict[str, int]:
    """Count how many rows contain at least one cue per pramana family."""
    counts = {label: 0 for label in PRAMANA_LABELS}
    for text in df["text"].astype(str):
        lowered = text.lower()
        for label, cues in HEURISTIC_CUES.items():
            if any(cue.lower() in lowered for cue in cues):
                counts[label] += 1
    return counts


def _default_anumana_count(df: pd.DataFrame) -> int:
    reason = df["candidate_reason"].astype(str)
    return int(reason.str.contains("No strong cue; default to Anumana", na=False).sum())


def build_review_priority(df: pd.DataFrame) -> pd.DataFrame:
    non_anumana = df[df["candidate_pramana"] != "Anumana"].copy()
    anumana_pool = df[df["candidate_pramana"] == "Anumana"]
    n_sample = min(ANUMANA_SAMPLE, len(anumana_pool))
    anumana_sample = anumana_pool.sample(n=n_sample, random_state=RANDOM_SEED)

    review = pd.concat([non_anumana, anumana_sample], ignore_index=True)
    review = review.sample(frac=1.0, random_state=RANDOM_SEED).reset_index(drop=True)
    review["review_priority"] = review["candidate_pramana"].apply(
        lambda x: "high" if x != "Anumana" else "baseline_sample"
    )
    return review


def write_distribution_report(df: pd.DataFrame, review: pd.DataFrame) -> None:
    ensure_reports_dir()

    total = len(df)
    pramana_dist = (
        df["candidate_pramana"]
        .value_counts()
        .reindex(PRAMANA_LABELS, fill_value=0)
        .rename_axis("candidate_pramana")
        .reset_index(name="count")
    )
    pramana_dist["percentage"] = (100.0 * pramana_dist["count"] / total).round(2)

    comp_cross = pd.crosstab(df["component_type"], df["candidate_pramana"], margins=True)
    comp_cross = comp_cross.reindex(columns=[*PRAMANA_LABELS, "All"], fill_value=0)

    cue_hits = _cue_hit_counts(df)
    cue_df = pd.DataFrame(
        [{"pramana": k, "rows_with_cue": v, "pct_of_corpus": round(100 * v / total, 2)} for k, v in cue_hits.items()]
    )

    default_anumana = _default_anumana_count(df)
    explicit_anumana = int((df["candidate_pramana"] == "Anumana").sum()) - default_anumana

    lines: list[str] = []
    lines.append("# AAEC Nyaya Distribution Analysis\n\n")
    lines.append(
        "Analysis of heuristic `candidate_pramana` labels on the AAEC annotation sheet "
        f"(`n={total}`). Generated by `dataset/build_aaec_review_priority.py`.\n\n"
    )

    lines.append("## 1. Overall candidate distribution\n\n")
    lines.append(dataframe_to_markdown(pramana_dist) + "\n\n")

    lines.append("## 2. Component type × candidate pramana\n\n")
    lines.append(dataframe_to_markdown(comp_cross.reset_index()) + "\n\n")

    lines.append("## 3. Lexical cue hit rates (substring heuristics)\n\n")
    lines.append(dataframe_to_markdown(cue_df) + "\n\n")
    lines.append(
        f"- Rows explicitly classified as Anumana via cues: **{explicit_anumana}** "
        f"({100 * explicit_anumana / total:.1f}%)\n"
    )
    lines.append(
        f"- Rows defaulting to Anumana (no cue match): **{default_anumana}** "
        f"({100 * default_anumana / total:.1f}%)\n\n"
    )

    lines.append("## 4. Priority review subset\n\n")
    lines.append(
        f"Exported `aaec_review_priority.csv` with **{len(review)}** rows:\n\n"
    )
    lines.append(
        f"- All non-Anumana rows: **{len(review[review['candidate_pramana'] != 'Anumana'])}**\n"
    )
    lines.append(
        f"- Random Anumana baseline sample: **{len(review[review['review_priority'] == 'baseline_sample'])}**\n\n"
    )
    review_dist = review["candidate_pramana"].value_counts().reindex(PRAMANA_LABELS, fill_value=0)
    lines.append("| Label | Review subset count |\n")
    lines.append("| --- | ---: |\n")
    for label in PRAMANA_LABELS:
        lines.append(f"| {label} | {int(review_dist[label])} |\n")
    lines.append("\n")

    lines.append("## 5. Why AAEC strongly favors Anumana\n\n")
    lines.append(
        "### Genre and discourse structure\n\n"
        "The AAEC corpus consists of **argumentative student essays** decomposed into "
        "MajorClaims, Claims, and Premises. This genre is inherently **inferential**: "
        "writers defend positions, draw consequences, and chain reasons together. Even "
        "when explicit markers like *because* or *therefore* are absent, the rhetorical "
        "function of most spans is still **reason-giving** rather than direct perception, "
        "testimony, or analogy.\n\n"
        "### Component-type skew\n\n"
        f"- **Premises** dominate the extracted pool ({int((df['component_type']=='Premise').sum())} of {total} "
        "in the annotation sheet sample) and function as supporting reasons — a natural "
        "fit for Anumana.\n"
        "- **MajorClaims** state positions to be argued, not sensory observations.\n"
        "- **Claims** are intermediate argumentative moves, again typically inferential.\n\n"
        "### Lexical cue scarcity\n\n"
        f"Only **{cue_hits['Pratyaksha']}** rows ({100 * cue_hits['Pratyaksha'] / total:.1f}%) contain "
        "Pratyaksha cues (observation, measurement, data, records, survey results). "
        f"**{cue_hits['Shabda']}** rows ({100 * cue_hits['Shabda'] / total:.1f}%) contain Shabda cues "
        "(according to, experts, studies, authorities). "
        f"**{cue_hits['Upamana']}** rows ({100 * cue_hits['Upamana'] / total:.1f}%) contain Upamana cues "
        "(like, similar to, analogous to, comparison).\n\n"
        "AAEC essays rarely cite primary data, field measurements, or formal authorities in the "
        "short spans extracted; they more often use general reasoning and opinion.\n\n"
        "### Heuristic default effect\n\n"
        f"**{default_anumana}** rows ({100 * default_anumana / total:.1f}%) received Anumana "
        "because **no pramana cue matched**. The default reflects the dominant argumentative "
        "function but amplifies the Anumana skew; many of these may be weak Anumana or "
        "unlabeled mixed rhetoric requiring human review.\n\n"
        "### False-positive Upamana from \"like\"\n\n"
        "Several Upamana assignments come from the substring **\"like\"** in non-analogical "
        "contexts (e.g., *would like to*, *is like anyone*). AAEC under-represents true "
        "Upamana (explicit comparison/analogy) while the heuristic over-triggers on common "
        "English function words.\n\n"
    )

    lines.append("## 6. Under-representation summary\n\n")
    lines.append("| Pramana | AAEC issue | Approx. share |\n")
    lines.append("| --- | --- | ---: |\n")
    for _, row in pramana_dist.iterrows():
        lines.append(
            f"| {row['candidate_pramana']} | "
            f"{'Dominant class' if row['candidate_pramana'] == 'Anumana' else 'Under-represented'} | "
            f"{row['percentage']}% |\n"
        )
    lines.append("\n")

    lines.append("## 7. Recommendations for collecting missing classes\n\n")
    lines.append("### Pratyaksha (direct perception / empirical observation)\n\n")
    lines.append(
        "- **Science lab reports** and field notes with explicit measurements, readings, and observations.\n"
        "- **News eyewitness** segments and citizen journalism with sensory verbs (*I saw, we measured, the sensor showed*).\n"
        "- **Medical/clinical charts** summarizing vitals, imaging, and examination findings.\n"
        "- **Survey methodology** excerpts reporting raw response counts and data tables.\n"
        "- **Product reviews** grounded in hands-on use (*after testing for two weeks, the battery lasted…*).\n\n"
    )
    lines.append("### Shabda (testimony / authoritative word)\n\n")
    lines.append(
        "- **Academic abstracts** with citation frames (*Smith et al. (2023) report that…*).\n"
        "- **Policy briefs** referencing government guidelines, WHO/CDC advisories, or legal statutes.\n"
        "- **Journalism** using *according to officials / researchers / the ministry*.\n"
        "- **Textbook** and encyclopedia definitional passages.\n"
        "- **Expert interview** transcripts with attributed claims.\n\n"
    )
    lines.append("### Upamana (analogy / comparison)\n\n")
    lines.append(
        "- **Op-ed analogies** with explicit *just as / similar to / analogous to* structures.\n"
        "- **Science popularization** comparing unfamiliar phenomena to familiar ones.\n"
        "- **Legal reasoning** precedents (*this case is like Brown v. Board in that…*).\n"
        "- **Debate** corpus arguments using comparative metaphors deliberately.\n"
        "- Filter for **multi-word analogy cues** to avoid false hits on *would like to*.\n\n"
    )
    lines.append("### Anumana (retain but calibrate)\n\n")
    lines.append(
        "- Keep AAEC as a strong **inferential backbone** but cap its share in training merges.\n"
        "- Use `aaec_review_priority.csv` to manually validate non-default Anumana and all "
        "non-Anumana candidates before merging into `real_world_dataset.csv`.\n"
        "- Combine AAEC with **balanced external slices** (target ≥50–100 examples per pramana per source).\n\n"
    )

    lines.append("## 8. Suggested next sources (beyond AAEC)\n\n")
    lines.append("| Source type | Pramana target | Rationale |\n")
    lines.append("| --- | --- | --- |\n")
    lines.append("| ArXiv/PubMed abstract snippets | Shabda, Pratyaksha | Citations + reported results |\n")
    lines.append("| WikiHow / instructional guides | Upamana, Anumana | Step analogies and causal chains |\n")
    lines.append("| Reddit r/AskScience answers | Shabda, Pratyaksha | Expert flairs + empirical checks |\n")
    lines.append("| Court opinion excerpts | Shabda, Upamana | Precedent and authority language |\n")
    lines.append("| IMDb/tech product reviews | Pratyaksha | First-hand experience reports |\n")
    lines.append("| Debate.org / IQ2 transcripts | Upamana, Anumana | Structured comparison + inference |\n\n")

    REPORT_OUT.write_text("".join(lines), encoding="utf-8")


def main() -> None:
    if not INPUT_CSV.is_file():
        raise FileNotFoundError(f"Missing {INPUT_CSV}. Run dataset/build_aaec_nyaya_annotation_sheet.py first.")

    df = pd.read_csv(INPUT_CSV)
    review = build_review_priority(df)

    OUTPUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    review.to_csv(OUTPUT_CSV, index=False, encoding="utf-8")
    write_distribution_report(df, review)

    print("AAEC Nyaya distribution analysis")
    print("=" * 50)
    print(f"Full sheet rows: {len(df)}")
    print("\nCandidate pramana distribution:")
    print(df["candidate_pramana"].value_counts().reindex(PRAMANA_LABELS, fill_value=0).to_string())
    print(f"\nReview priority rows: {len(review)}")
    print(f"  Non-Anumana (all): {len(review[review['candidate_pramana'] != 'Anumana'])}")
    print(f"  Anumana sample: {len(review[review['review_priority'] == 'baseline_sample'])}")
    print(f"\nSaved: {OUTPUT_CSV}")
    print(f"Saved: {REPORT_OUT}")


if __name__ == "__main__":
    main()
