"""
Expanded held-out evaluation on dataset/test_set.csv.

Outputs:
  - reports/heldout_evaluation.md
  - reports/csv/heldout_per_class_metrics.csv
  - reports/figures/heldout_confusion_matrix.png

Requires trained model artifacts under models/.

Usage:
    python reports/generate_heldout_evaluation.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import joblib
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_recall_fscore_support,
)

_ROOT = Path(__file__).resolve().parent.parent
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from classification.embedder import generate_embeddings
from reports._common import LABELS, apply_plot_style, dataframe_to_markdown, ensure_reports_dir, save_dataframe_csv


def load_model_and_data():
    model_path = _ROOT / "models" / "nyaya_model.pkl"
    le_path = _ROOT / "models" / "label_encoder.pkl"
    test_path = _ROOT / "dataset" / "test_set.csv"

    for p in (model_path, le_path, test_path):
        if not p.is_file():
            raise FileNotFoundError(f"Missing required file: {p}")

    model = joblib.load(model_path)
    le = joblib.load(le_path)
    tdf = pd.read_csv(test_path)
    texts = tdf["text"].astype(str).tolist()
    y_true = le.transform(tdf["pramana_label"].astype(str))
    X = generate_embeddings(texts)
    y_pred = model.predict(X)
    y_proba = model.predict_proba(X)
    return model, le, tdf, texts, y_true, y_pred, y_proba


def main() -> None:
    ensure_reports_dir()
    fig_dir = _ROOT / "reports" / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)

    _, le, _, _, y_true, y_pred, _ = load_model_and_data()
    classes = list(le.classes_)

    prec, rec, f1, support = precision_recall_fscore_support(
        y_true, y_pred, labels=list(range(len(classes))), zero_division=0
    )
    per_class = pd.DataFrame(
        {
            "Class": classes,
            "Precision": np.round(prec, 4),
            "Recall": np.round(rec, 4),
            "F1": np.round(f1, 4),
            "Support": support.astype(int),
        }
    )
    save_dataframe_csv(per_class, _ROOT / "reports" / "csv" / "heldout_per_class_metrics.csv")

    accuracy = float(accuracy_score(y_true, y_pred))
    macro_f1 = float(f1_score(y_true, y_pred, average="macro", zero_division=0))
    weighted_f1 = float(f1_score(y_true, y_pred, average="weighted", zero_division=0))
    bal_acc = float(balanced_accuracy_score(y_true, y_pred))

    cm = confusion_matrix(y_true, y_pred, labels=list(range(len(classes))))

    apply_plot_style()
    plt.figure(figsize=(6.5, 5.5))
    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues",
        xticklabels=classes,
        yticklabels=classes,
        cbar_kws={"label": "Count"},
        linewidths=0.5,
        linecolor="white",
    )
    plt.ylabel("True label")
    plt.xlabel("Predicted label")
    plt.title(f"Held-out test confusion matrix (accuracy = {accuracy:.2%})")
    plt.tight_layout()
    cm_path = fig_dir / "heldout_confusion_matrix.png"
    plt.savefig(cm_path, bbox_inches="tight")
    plt.close()

    report_txt = classification_report(
        y_true, y_pred, target_names=classes, digits=4, zero_division=0
    )

    lines: list[str] = []
    lines.append("# InferAI — Held-Out Test Evaluation\n\n")
    lines.append(
        "Per-class and aggregate metrics on the curated held-out set "
        "(`dataset/test_set.csv`, n=200). Generated by `reports/generate_heldout_evaluation.py`.\n\n"
    )

    lines.append("## Aggregate metrics\n\n")
    agg = pd.DataFrame(
        [
            {"Metric": "Accuracy", "Value": round(accuracy, 4)},
            {"Metric": "Macro F1", "Value": round(macro_f1, 4)},
            {"Metric": "Weighted F1", "Value": round(weighted_f1, 4)},
            {"Metric": "Balanced accuracy", "Value": round(bal_acc, 4)},
        ]
    )
    lines.append(dataframe_to_markdown(agg) + "\n\n")

    lines.append("## Per-class metrics\n\n")
    lines.append(dataframe_to_markdown(per_class) + "\n\n")

    lines.append("## Sklearn classification report\n\n")
    lines.append("```text\n")
    lines.append(report_txt.strip() + "\n")
    lines.append("```\n\n")

    lines.append("## Confusion matrix\n\n")
    lines.append(f"![Held-out confusion matrix](figures/heldout_confusion_matrix.png)\n\n")

    lines.append("## Interpretation\n\n")
    lines.append(
        f"Held-out accuracy ({accuracy:.1%}) is substantially lower than in-distribution "
        "random holdout (~99.6%), indicating **distribution shift** between template-heavy "
        "training data and curated real-world test examples. "
        "Balanced accuracy and macro F1 penalize the skew where some classes (e.g. Upamana) "
        "achieve high recall while others (e.g. Shabda, Pratyaksha) trade precision and recall.\n"
    )

    out = _ROOT / "reports" / "heldout_evaluation.md"
    out.write_text("".join(lines), encoding="utf-8")
    print(f"Wrote {out}")
    print(f"Wrote {cm_path}")


if __name__ == "__main__":
    main()
